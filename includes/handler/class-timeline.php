<?php
/**
 * Timeline handler.
 *
 * This contains the default Account handlers.
 *
 * @package Enable_Mastodon_Apps
 */

namespace Enable_Mastodon_Apps\Handler;

use WP_REST_Request;
use Enable_Mastodon_Apps\Handler\Handler;
use Enable_Mastodon_Apps\Entity\Timeline as Timeline_Entity;

/**
 * This is the class that implements the default handler for all Timeline endpoints.
 *
 * @since 0.7.0
 *
 * @package Enable_Mastodon_Apps
 */
class Timeline extends Handler {
	public function __construct() {
		$this->register_hooks();
	}

	public function register_hooks() {
		add_filter( 'mastodon_api_timelines', array( $this, 'api_timelines' ), 10, 2 );
		add_filter( 'mastodon_api_tag_timeline', array( $this, 'api_tag_timeline' ), 10, 2 );
		add_filter( 'mastodon_api_public_timeline', array( $this, 'api_public_timeline' ), 10, 2 );
		add_filter( 'mastodon_api_timeline_supports_deduplication', '__return_true' );
	}

	/**
	 * Handle timeline requests.
	 *
	 * @param WP_REST_Response|null $statuses The statuses data.
	 * @param WP_REST_Request       $request  The request object.
	 *
	 * @return WP_REST_Response The statuses as a REST response.
	 */
	public function api_timelines( $statuses, $request ) {
		$args = $this->get_posts_query_args( array(), $request );
		/**
		 * Filter the query arguments for the timeline.
		 *
		 * @param array           $args    The query arguments.
		 * @param WP_REST_Request $request The request object.
		 *
		 * @return array The modified query arguments.
		 */
		$args = apply_filters( 'mastodon_api_timelines_args', $args, $request );

		if ( empty( $args ) ) {
			return array();
		}

		if ( ! empty( $args['mastodon_api_deduplicate'] ) ) {
			$args['orderby'] = 'ID';
			$args['order']   = 'DESC';
			$args = $this->deduplicate_query_args( $args, $request );
		}

		return $this->get_posts( $args, $request->get_param( 'min_id' ), $request->get_param( 'max_id' ) );
	}

	/**
	 * Select one representation of each shared cached object before pagination.
	 *
	 * Set mastodon_api_deduplicate to the post types being added, or true to
	 * compare all types. Both sides of a duplicate must satisfy the original query, including any
	 * integration's recipient restrictions. Boosts are separate timeline events.
	 * Existing post IDs remain the IDs used for status actions and cursors.
	 *
	 * @param array           $args    Timeline query arguments.
	 * @param WP_REST_Request $request Timeline request.
	 * @return array Query arguments excluding duplicate representations.
	 */
	public function deduplicate_query_args( $args, $request ) {
		global $wpdb;

		if ( count( (array) $args['post_type'] ) < 2 ) {
			return $args;
		}

		$query_args = array_merge(
			$args,
			array(
				'fields'         => 'ids',
				'posts_per_page' => -1,
				'nopaging'       => true,
				'orderby'        => 'none',
				'no_found_rows'  => true,
				'cache_results'  => false,
			)
		);
		unset( $query_args['offset'], $query_args['paged'] );
		$query = new \WP_Query();
		// Generate the fully scoped SQL without fetching the entire timeline.
		$skip_query = static function ( $posts, $candidate_query ) use ( $query ) {
			return $candidate_query === $query ? array() : $posts;
		};
		$identity_fields = static function ( $fields, $candidate_query ) use ( $query, $wpdb ) {
			return $candidate_query === $query ? "{$wpdb->posts}.ID, {$wpdb->posts}.guid, {$wpdb->posts}.post_type" : $fields;
		};
		add_filter( 'posts_pre_query', $skip_query, PHP_INT_MAX, 2 );
		add_filter( 'posts_fields', $identity_fields, PHP_INT_MAX, 2 );
		try {
			$query->query( $query_args );
		} finally {
			remove_filter( 'posts_pre_query', $skip_query, PHP_INT_MAX );
			remove_filter( 'posts_fields', $identity_fields, PHP_INT_MAX );
		}

		// Compare GUIDs case sensitively: URL paths may be case sensitive.
		$eligible_sql = $query->request;
		$sources      = $args['mastodon_api_deduplicate'];
		if ( is_array( $sources ) ) {
			// Start with the cache being added, rather than grouping the entire archive.
			$placeholders = implode( ', ', array_fill( 0, count( $sources ), '%s' ) );
			$sql = $wpdb->prepare( "SELECT DISTINCT BINARY guid FROM ({$eligible_sql}) eligible WHERE guid <> '' AND post_type IN ({$placeholders})", $sources ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQLPlaceholders.UnfinishedPrepare
		} else {
			$sql = "SELECT MIN(guid) FROM ({$eligible_sql}) eligible
				WHERE guid <> '' GROUP BY BINARY guid HAVING COUNT(DISTINCT post_type) > 1";
		}
		// The subqueries are generated by WP_Query, with the original visibility filters.
		$guids = $wpdb->get_col( $sql ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared, WordPress.DB.DirectDatabaseQuery
		if ( ! $guids ) {
			return $args;
		}
		$placeholders = implode( ', ', array_fill( 0, count( $guids ), '%s' ) );
		$sql = $wpdb->prepare( "SELECT ID, guid, post_type FROM ({$eligible_sql}) eligible WHERE BINARY guid IN ({$placeholders}) ORDER BY ID ASC", $guids ); // phpcs:ignore WordPress.DB.PreparedSQL.InterpolatedNotPrepared, WordPress.DB.PreparedSQLPlaceholders.UnfinishedPrepare
		$rows = $wpdb->get_results( $sql ); // phpcs:ignore WordPress.DB.PreparedSQL.NotPrepared, WordPress.DB.DirectDatabaseQuery
		$types = array();
		foreach ( $rows as $row ) {
			$types[ $row->guid ][ $row->post_type ] = true;
		}
		$ids = array();
		foreach ( $rows as $row ) {
			if ( count( $types[ $row->guid ] ) > 1 ) {
				$ids[] = (int) $row->ID;
			}
		}
		_prime_post_caches( $ids, false, true );
		$objects  = array();
		$excluded = array();
		foreach ( $ids as $id ) {
			$post = get_post( $id );
			/**
			 * Identify a cached timeline object without rendering its status.
			 *
			 * Return false for separate events such as boosts. Return null when
			 * the integration needs its full status to determine event identity.
			 *
			 * @param string|false|null $identity Object GUID, false for an event, null if unknown.
			 * @param \WP_Post        $post     Cached post.
			 * @param WP_REST_Request $request  Timeline request.
			 */
			$key = apply_filters( 'mastodon_api_timeline_post_identity', null, $post, $request );
			if ( false === $key ) {
				continue;
			}
			// Older integrations expose boost identity only through their status.
			if ( null === $key ) {
				$key    = $post->guid;
				$status = apply_filters( 'mastodon_api_status', null, $post->ID, array() );
				if ( ! $status instanceof \Enable_Mastodon_Apps\Entity\Status || ! $status->is_valid() || isset( $status->reblog ) ) {
					continue;
				}
			}
			/**
			 * Choose the representation of an object cached by multiple integrations.
			 *
			 * Higher values win. Equal priorities retain the oldest cached post ID.
			 * Integrations retain ownership of their cache and reaction metadata.
			 *
			 * @param int             $priority Representation priority, default zero.
			 * @param \WP_Post        $post     Cached post.
			 * @param WP_REST_Request $request  Timeline request.
			 */
			$priority = (int) apply_filters( 'mastodon_api_timeline_post_priority', 0, $post, $request );
			if ( ! isset( $objects[ $key ] ) ) {
				$objects[ $key ] = array(
					'id'       => $post->ID,
					'priority' => $priority,
				);
			} elseif ( $priority > $objects[ $key ]['priority'] ) {
				$excluded[]      = $objects[ $key ]['id'];
				$objects[ $key ] = array(
					'id'       => $post->ID,
					'priority' => $priority,
				);
			} else {
				$excluded[] = $post->ID;
			}
		}
		if ( ! empty( $args['post__in'] ) ) {
			$args['post__in'] = array_values( array_diff( $args['post__in'], $excluded ) );
			if ( ! $args['post__in'] ) {
				$args['post__in'] = array( 0 );
			}
		} else {
			$args['post__not_in'] = array_unique( array_merge( (array) ( $args['post__not_in'] ?? array() ), $excluded ) );
		}
		return $args;
	}

	/**
	 * Handle tag timeline requests.
	 *
	 * @param WP_REST_Response|null $statuses The statuses data.
	 * @param WP_REST_Request       $request  The request object.
	 *
	 * @return WP_REST_Response The statuses as a REST response.
	 */
	public function api_tag_timeline( $statuses, $request ) {
		$args        = $this->get_posts_query_args( array(), $request );
		$args['tag'] = $request->get_param( 'hashtag' );

		$ppp_param = $request->get_param( 'limit' );
		if ( null !== $ppp_param ) {
			$args['posts_per_page'] = $ppp_param;
		}

		/**
		 * Filter the query arguments for the timeline.
		 *
		 * @param array           $args    The query arguments.
		 * @param WP_REST_Request $request The request object.
		 *
		 * @return array The modified query arguments.
		 */
		$args = apply_filters( 'mastodon_api_timelines_args', $args, $request );

		return $this->get_posts( $args, $request->get_param( 'min_id' ), $request->get_param( 'max_id' ) );
	}

	/**
	 * Handle public timeline requests.
	 *
	 * @param WP_REST_Response|null $statuses The statuses data.
	 * @param WP_REST_Request       $request  The request object.
	 *
	 * @return WP_REST_Response The statuses as a REST response.
	 */
	public function api_public_timeline( $statuses, $request ) {
		$args = $this->get_posts_query_args( array(), $request );
		if ( empty( $args ) ) {
			return array();
		}

		// Only get the published posts for the public timeline.
		$args['post_status'] = 'publish';

		/**
		 * Filter the query arguments for the timeline.
		 *
		 * @param array           $args    The query arguments.
		 * @param WP_REST_Request $request The request object.
		 *
		 * @return array The modified query arguments.
		 */
		$args = apply_filters( 'mastodon_api_timelines_args', $args, $request );

		if ( rest_sanitize_boolean( $request->get_param( 'local' ) ) ) {
			// Cached remote posts and received comments have no local WordPress author.
			// Keep locally authored replies even when their parent post is remote.
			$args['author__not_in'] = array_unique( array_merge( (array) ( $args['author__not_in'] ?? array() ), array( 0 ) ) );
		}

		return $this->get_posts( $args, $request->get_param( 'min_id' ), $request->get_param( 'max_id' ) );
	}
}
